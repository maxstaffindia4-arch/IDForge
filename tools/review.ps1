# IDForge phase-review launcher.
# Builds a self-contained Release copy, prints branch/commit, runs the
# screenshot-producing tests, verifies the shots, then launches the app.
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$gitExe = (Get-Command git -ErrorAction SilentlyContinue).Source
if (-not $gitExe -and (Test-Path "C:\Tools\MinGit\cmd\git.exe")) { $gitExe = "C:\Tools\MinGit\cmd\git.exe" }
# Prefer the SDK install under the user profile — a PATH dotnet may be a
# runtime-only host with no SDKs ("No .NET SDKs were found").
$dotnetExe = "$env:USERPROFILE\.dotnet\dotnet.exe"
if (-not (Test-Path $dotnetExe)) {
    $dotnetExe = (Get-Command dotnet -ErrorAction SilentlyContinue).Source
}
if (-not $dotnetExe -or -not (Test-Path $dotnetExe)) { throw "dotnet SDK not found in $env:USERPROFILE\.dotnet or on PATH" }

$branch = (& $gitExe rev-parse --abbrev-ref HEAD 2>$null)
$hash = (& $gitExe rev-parse --short HEAD 2>$null)
Write-Host "Branch: $branch  Commit: $hash" -ForegroundColor Cyan

# ---------------------------------------------------------------------------
# FIX 5 — screenshot step. The New card window is captured at 860x620,
# 1100x700 and 1280x800 by the same test run that proves the layout rules
# (icons render, no overlap/clip, nav rail states, owner decisions).
# ---------------------------------------------------------------------------
$shotsDir = Join-Path $root "docs\redesign\shots"
$expectedShots = @(
    "newcard-860x620.png",
    "newcard-1100x700.png",
    "newcard-1280x800.png",
    "newcard-icons-1280x800.png",
    "nav-expanded-1280x800.png",
    "nav-collapsed-860x620.png"
)

Write-Host "Running screenshot + layout tests..." -ForegroundColor Cyan
& $dotnetExe test tests\IDForge.Tests\IDForge.Tests.csproj `
    --filter "FullyQualifiedName~NewCardParityTests|FullyQualifiedName~FixJPartATests|FullyQualifiedName~IconGlyphTests|FullyQualifiedName~FixKPartATests|FullyQualifiedName~FixPassTests" `
    --nologo
if ($LASTEXITCODE -ne 0) {
    Write-Host "TESTS FAILED (exit $LASTEXITCODE) - app not launched." -ForegroundColor Red
    exit $LASTEXITCODE
}
Write-Host "Tests passed - screenshots regenerated by the same run." -ForegroundColor Green

# --- Per-screenshot checks --------------------------------------------------
# Semantic checks (icons rendered, no overlapping/clipped text, nav rail
# visible, no menu bar, no Save draft, About only in the rail) are asserted
# by the tests above. Here we verify each file exists, is fresh and is not
# a blank image, plus a pixel probe that the nav rail strip has content.
Add-Type -AssemblyName System.Drawing
$failures = @()
foreach ($shot in $expectedShots) {
    $path = Join-Path $shotsDir $shot
    if (-not (Test-Path $path)) { $failures += "$shot MISSING"; continue }
    $age = (Get-Date) - (Get-Item $path).LastWriteTime
    if ($age.TotalMinutes -gt 30) { $failures += "$shot STALE ($([int]$age.TotalMinutes) min old)" }
    $bmp = [System.Drawing.Bitmap]::FromFile($path)
    try {
        # Sample a grid of pixels; a rendered window has many distinct colors.
        $colors = @{}
        for ($x = 0; $x -lt $bmp.Width; $x += 37) {
            for ($y = 0; $y -lt $bmp.Height; $y += 37) {
                $colors[$bmp.GetPixel($x, $y).ToArgb()] = $true
            }
        }
        if ($colors.Count -lt 8) { $failures += "$shot looks blank ($($colors.Count) colors)" }
    } finally { $bmp.Dispose() }
    Write-Host ("  shot: {0} ({1} KB)" -f $shot, [int]((Get-Item $path).Length / 1KB))
}

# Nav rail visible: the left ~208 px strip of the expanded shot must contain
# more than one color (rail background + icons/labels).
$navShot = Join-Path $shotsDir "nav-expanded-1280x800.png"
if (Test-Path $navShot) {
    $bmp = [System.Drawing.Bitmap]::FromFile($navShot)
    try {
        $colors = @{}
        for ($x = 8; $x -lt 200; $x += 6) {
            for ($y = 40; $y -lt $bmp.Height - 40; $y += 6) {
                $colors[$bmp.GetPixel($x, $y).ToArgb()] = $true
            }
        }
        if ($colors.Count -lt 4) { $failures += "nav-expanded rail strip looks empty ($($colors.Count) colors)" }
        else { Write-Host "  check: nav rail strip has $($colors.Count) distinct colors" -ForegroundColor DarkGray }
    } finally { $bmp.Dispose() }
}

if ($failures.Count -gt 0) {
    Write-Host "SCREENSHOT CHECKS FAILED:" -ForegroundColor Red
    $failures | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
    exit 1
}
Write-Host "Screenshot checks passed." -ForegroundColor Green

# ---------------------------------------------------------------------------
Write-Host "Publishing..." -ForegroundColor Cyan
& $dotnetExe publish src\IDForge -c Release -r win-x64 --self-contained true -o publish\idforge
if ($LASTEXITCODE -ne 0) {
    Write-Host "PUBLISH FAILED (exit $LASTEXITCODE) - app not launched." -ForegroundColor Red
    exit $LASTEXITCODE
}

$exe = Join-Path $root "publish\idforge\IDForge.exe"
Write-Host "Launching $exe" -ForegroundColor Green
Start-Process $exe

# NAV RAIL check: capture the LIVE window (not a test render) and prove the
# left strip contains the rail — fails the run if the rail looks empty.
Start-Sleep -Seconds 8
& powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot "capture-live-shot.ps1") -OutDir $shotsDir
if ($LASTEXITCODE -ne 0) {
    Write-Host "LIVE WINDOW CHECK FAILED - see output above." -ForegroundColor Red
    exit $LASTEXITCODE
}
